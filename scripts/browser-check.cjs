const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const { randomUUID } = require('node:crypto');

async function main() {
  const baseUrl = process.env.BASE_URL || 'http://localhost:3000';
  const executablePath = process.env.CHROME_PATH || (process.platform === 'win32' ? 'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe' : undefined);
  const browser = await chromium.launch({ headless: true, ...(executablePath ? { executablePath } : {}) });
  const page = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1 });
  try {
    await page.goto(baseUrl);
    if (process.env.SCREENSHOT === '1') { fs.mkdirSync('.artifacts', { recursive: true }); await page.screenshot({ path: '.artifacts/landing-mobile.png', fullPage: true }); await page.setViewportSize({ width: 1280, height: 900 }); await page.screenshot({ path: '.artifacts/landing-desktop.png', fullPage: true }); await page.setViewportSize({ width: 390, height: 844 }); }
    await page.getByRole('button', { name: 'Demoni boshlash' }).click();
    await page.waitForURL('**/dashboard');
    await page.getByRole('heading', { name: /Salom, Demo o‘quvchi/ }).waitFor();
    if (process.env.SCREENSHOT === '1') await page.screenshot({ path: '.artifacts/dashboard-mobile.png', fullPage: true });
    assert.match(await page.locator('main').innerText(), /Salom, Demo o‘quvchi/);
    await page.locator('.subject-card').filter({ hasText: 'Kimyo' }).getByRole('link', { name: /Mavzularni ko‘rish/ }).click();
    await page.locator('.topic-card').filter({ hasText: 'Atom tuzilishi' }).getByRole('link', { name: /Boshlash/ }).click();
    await page.getByRole('link', { name: /Kartochkalarga o‘tish/ }).click();
    await page.getByRole('button', { name: /Savol. Javobni/ }).click();
    await page.getByRole('button', { name: /Javob. Savolni ko‘rish/ }).click();
    await page.getByRole('button', { name: /Testga o‘tish/ }).click();
    await page.waitForURL('**/test/**');
    const firstAttempt = page.url();
    const questions = page.locator('fieldset.question');
    await questions.first().waitFor();
    assert.equal(await questions.count(), 5);
    for (let i = 0; i < 5; i++) await questions.nth(i).locator('input[type=radio]').nth(i === 0 ? 1 : [0,2,1,1,2][i]).check();
    await page.reload();
    await questions.first().locator('input:checked').first().waitFor();
    assert.equal(await questions.first().locator('input:checked').count(), 1);
    await page.getByRole('button', { name: /Javoblarni tekshirish/ }).click();
    await page.waitForURL('**/natija/**');
    await page.getByRole('heading', { name: 'Natijangiz' }).waitFor();
    assert.match(await page.locator('main').innerText(), /E’tibor beriladigan tushunchalar/);
    const resultUrl = page.url();
    await page.reload();
    assert.equal(page.url(), resultUrl);
    await page.getByRole('link', { name: /Tushunchani ko‘rish/ }).first().click();
    await page.getByLabel('Javobingiz').fill('proton va neytron');
    await page.getByRole('button', { name: 'Mashqni tekshirish' }).click();
    await page.waitForURL('**/takrorlash/**?practice=correct');
    assert.match(await page.locator('main').innerText(), /To‘g‘ri!/);
    await page.getByRole('button', { name: /Yangi testni boshlash/ }).click();
    await page.waitForURL('**/test/**');
    assert.notEqual(page.url(), firstAttempt);
    const retryQuestions = page.locator('fieldset.question');
    await retryQuestions.first().waitFor();
    for (let i = 0; i < 5; i++) await retryQuestions.nth(i).locator('input[type=radio]').nth([0,2,1,1,2][i]).check();
    await page.getByRole('button', { name: /Javoblarni tekshirish/ }).click();
    await page.waitForURL('**/natija/**');
    await page.getByRole('heading', { name: 'Natijangiz' }).waitFor();
    assert.match(await page.locator('main').innerText(), /Oldingi urinishdan \+1 ta ko‘p/);
    await page.getByRole('link', { name: /Boshqaruvga qaytish/ }).click();
    await page.waitForURL('**/dashboard');
    await page.getByRole('heading', { name: /Salom, Demo o‘quvchi/ }).waitFor();
    assert.match(await page.locator('main').innerText(), /Jami XP/);
    await page.getByRole('link', { name: 'Profil' }).click();
    await page.waitForURL('**/profil');
    await page.getByRole('heading', { name: 'Profil' }).waitFor();
    assert.match(await page.locator('main').innerText(), /32/);
    await page.reload();
    await page.locator('.stat strong').first().filter({ hasText: '32' }).waitFor();
    assert.match(await page.locator('main').innerText(), /32/);
    await page.getByRole('button', { name: 'Chiqish' }).click();
    await page.goto(resultUrl);
    await page.waitForURL('**/kirish');
    const email = `${randomUUID()}@example.test`;
    await page.getByRole('link', { name: 'Ro‘yxatdan o‘ting' }).click();
    await page.getByLabel('Taxallus').fill('Sinov o‘quvchi');
    await page.getByLabel('Elektron pochta').fill(email);
    await page.getByLabel('Parol (kamida 8 belgi)').fill('TestPassword123!');
    await page.getByRole('button', { name: 'Hisob yaratish' }).click();
    await page.waitForURL('**/dashboard');
    await page.getByRole('heading', { name: /Sinov o‘quvchi/ }).waitFor();
    await page.goto(resultUrl);
    await page.getByRole('heading', { name: 'Bu manzil mavjud emas' }).waitFor();
    assert.match(await page.locator('main').innerText(), /Bu manzil mavjud emas/);
    await page.getByRole('link', { name: 'Profil' }).click();
    await page.getByLabel('Taxallus').fill('Yangi taxallus');
    await page.getByRole('button', { name: 'Saqlash' }).click();
    await page.waitForURL('**/profil?saved=1');
    await page.getByRole('button', { name: 'Chiqish' }).click();
    await page.waitForURL(`${baseUrl}/`);
    await page.locator('.top-nav').getByRole('link', { name: 'Kirish' }).click();
    await page.getByLabel('Elektron pochta').fill(email);
    await page.getByLabel('Parol').fill('TestPassword123!');
    await page.getByRole('button', { name: 'Kirish' }).click();
    await page.waitForURL('**/dashboard');
    await page.getByRole('heading', { name: /Yangi taxallus/ }).waitFor();
    console.log('Browser flow passed: demo loop, refresh, access control, registration, profile, and sign-in.');
  } finally { await browser.close(); }
}
main().catch(error => { console.error(error); process.exitCode = 1; });
